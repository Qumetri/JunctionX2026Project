/* C118 ics (calendar file for move day and reminders) */
function IcsDemo() {
  const [message, setMessage] = useState<string | null>(null);
  const download = () => {
    const events: EventAttributes[] = [
      {
        start: [2026, 11, 14, 8, 0],
        duration: { hours: 4 },
        title: 'Move day: movers arrive',
        description: 'Keys, meter photos and the checklist are in the Life Moments app.',
        location: 'Kallio, Helsinki',
        alarms: [
          {
            action: 'display',
            description: 'Move day in 1 hour',
            trigger: { hours: 1, before: true },
          },
        ],
      },
      {
        start: [2026, 10, 31, 9, 0],
        duration: { minutes: 30 },
        title: 'Reminder: notify landlord (written)',
        location: 'Espoo',
      },
    ];
    const { error, value } = createEvents(events);
    if (error || !value) {
      setMessage('Could not build the calendar file.');
      return;
    }
    const url = URL.createObjectURL(new Blob([value], { type: 'text/calendar;charset=utf-8' }));
    const link = document.createElement('a');
    link.href = url;
    link.download = 'move-day.ics';
    link.click();
    URL.revokeObjectURL(url);
    setMessage('Calendar file downloaded (2 events).');
  };
  return (
    <div className="b3-stack">
      <div className="row">
        <button type="button" className="btn btn--primary" onClick={download}>
          Download move-day calendar (.ics)
        </button>
      </div>
      {message && (
        <p className="b3-hint" role="status">
          {message}
        </p>
      )}
    </div>
  );
}

