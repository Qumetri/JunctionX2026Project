/* C113 React PDF Renderer (checklist PDF generated in the browser) */
const pdfStyles = StyleSheet.create({
  page: { padding: 36, fontSize: 11, fontFamily: 'Helvetica' },
  title: { fontSize: 18, marginBottom: 6 },
  subtitle: { fontSize: 10, color: '#5b6785', marginBottom: 16 },
  row: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    borderBottomWidth: 1,
    borderBottomColor: '#d9dfeb',
    paddingVertical: 6,
  },
});

function ChecklistPdf({ items }: { items: string[] }) {
  return (
    <Document title="Moving checklist">
      <Page size="A4" style={pdfStyles.page}>
        <Text style={pdfStyles.title}>Moving checklist</Text>
        <Text style={pdfStyles.subtitle}>
          Move date 14.11.2026 · Kallio to Espoo · generated by Life Moments demo
        </Text>
        {items.map((item) => (
          <View key={item} style={pdfStyles.row}>
            <Text>{item}</Text>
            <Text>[ ]</Text>
          </View>
        ))}
      </Page>
    </Document>
  );
}

function PdfRendererDemo() {
  const [href, setHref] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    return () => {
      if (href) URL.revokeObjectURL(href);
    };
  }, [href]);

  const build = async () => {
    setBusy(true);
    try {
      const blob = await pdf(<ChecklistPdf items={CHECKLIST_ITEMS} />).toBlob();
      setHref((prev) => {
        if (prev) URL.revokeObjectURL(prev);
        return URL.createObjectURL(blob);
      });
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="b3-stack">
      <div className="row">
        <button type="button" className="btn btn--primary" onClick={build} disabled={busy}>
          {busy ? 'Building PDF...' : 'Build checklist PDF'}
        </button>
        {href && (
          <a className="btn" href={href} download="moving-checklist.pdf">
            Download PDF
          </a>
        )}
      </div>
      <p className="b3-hint">
        {CHECKLIST_ITEMS.length} items, A4, generated in the browser. Nothing is uploaded.
      </p>
    </div>
  );
}

/* C114 React PDF (viewer for policy-terms PDFs in data/opendata) */
pdfjs.GlobalWorkerOptions.workerSrc = pdfWorkerUrl;

function PdfViewerDemo() {
  const [pages, setPages] = useState(0);
  const [page, setPage] = useState(1);
  const [failed, setFailed] = useState(false);

  if (failed) {
    return (
      <Unavailable>
        The sample PDF could not be opened in this browser. The other demos are not affected.
      </Unavailable>
    );
  }

  return (
    <div className="b3-stack">
      <div className="b3-pdf">
        <PdfDocument
          file={policyPdfUrl}
          onLoadSuccess={({ numPages }) => setPages(numPages)}
          onLoadError={() => setFailed(true)}
          loading={<p className="b3-hint">Opening PDF...</p>}
        >
          <PdfPage
            pageNumber={page}
            width={420}
            renderTextLayer={false}
            renderAnnotationLayer={false}
          />
        </PdfDocument>
      </div>
      <div className="row">
        <button
          type="button"
          className="btn"
          disabled={page <= 1}
          onClick={() => setPage((p) => p - 1)}
        >
          Previous
        </button>
        <span className="b3-hint" role="status">
          Page {page} of {pages || '…'}
        </span>
        <button
          type="button"
          className="btn"
          disabled={pages === 0 || page >= pages}
          onClick={() => setPage((p) => p + 1)}
        >
          Next
        </button>
      </div>
      <p className="b3-hint">Sample file: data/opendata/pronto/D1_2026.pdf</p>
    </div>
  );
}

