/* C116 html2canvas (shareable image of the summary card) */
function CaptureDemo() {
  const cardRef = useRef<HTMLDivElement>(null);
  const [image, setImage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const capture = async () => {
    if (!cardRef.current) return;
    try {
      const canvas = await html2canvas(cardRef.current, { backgroundColor: null, scale: 2 });
      setImage(canvas.toDataURL('image/png'));
      setError(null);
    } catch {
      setError('Could not capture the card in this browser.');
    }
  };

  return (
    <div className="b3-stack">
      <div ref={cardRef} className="b3-summary-card">
        <span className="b3-hint">Life Moments</span>
        <strong>Move ready: 78 %</strong>
        <span className="b3-hint">14 Nov 2026 · 12 of 18 tasks done</span>
      </div>
      <div className="row">
        <button type="button" className="btn" onClick={capture}>
          Capture share image
        </button>
      </div>
      {error && <Unavailable>{error}</Unavailable>}
      {image && <img className="b3-shot" src={image} alt="Captured summary card" />}
    </div>
  );
}

