/* C120 assistant-ui (optional chat about the plan, with a local rule-based answer) */
const chatAdapter: ChatModelAdapter = {
  async run({ messages }) {
    const last = messages[messages.length - 1];
    const question = last.content
      .map((part) => (part.type === 'text' ? part.text : ''))
      .join(' ')
      .toLowerCase();
    let answer =
      'I can help with dates, movers, pets and travel cover. Try asking about the van or the cat.';
    if (question.includes('van') || question.includes('parking')) {
      answer =
        'Apply for the parking permit at least 7 days before the move. Keep the permit visible on the windscreen.';
    } else if (question.includes('pet') || question.includes('cat') || question.includes('dog')) {
      answer =
        'Check the vaccination record is under 12 months old, and book transport 3 weeks ahead.';
    } else if (question.includes('mover') || question.includes('move')) {
      answer =
        'Book movers six weeks ahead. Compare three written quotes and ask for a fixed price.';
    }
    return { content: [{ type: 'text', text: answer }] };
  },
};

function ChatDemo() {
  const runtime = useLocalRuntime(chatAdapter);
  return (
    <AssistantRuntimeProvider runtime={runtime}>
      <ThreadPrimitive.Root className="b3-chat">
        <ThreadPrimitive.Viewport className="b3-chat__viewport">
          <ThreadPrimitive.Messages>
            {() => (
              <MessagePrimitive.Root className="b3-chat__msg">
                <MessagePrimitive.Content />
              </MessagePrimitive.Root>
            )}
          </ThreadPrimitive.Messages>
        </ThreadPrimitive.Viewport>
        <ComposerPrimitive.Root className="b3-chat__composer">
          <ComposerPrimitive.Input
            className="b3-input"
            placeholder="Ask about the van, the cat or the movers"
          />
          <ComposerPrimitive.Send className="btn btn--primary">Send</ComposerPrimitive.Send>
        </ComposerPrimitive.Root>
      </ThreadPrimitive.Root>
    </AssistantRuntimeProvider>
  );
}

/* C121 React Signature Canvas (van rental agreement) */
function SignatureDemo() {
  const padRef = useRef<SignatureCanvas>(null);
  const [signed, setSigned] = useState<string | null>(null);
  return (
    <div className="b3-stack">
      <div className="b3-sig">
        <SignatureCanvas
          ref={padRef}
          penColor="#101a33"
          canvasProps={{ className: 'b3-sig__canvas', width: 480, height: 160 }}
        />
      </div>
      <div className="row">
        <button type="button" className="btn" onClick={() => padRef.current?.clear()}>
          Clear
        </button>
        <button
          type="button"
          className="btn btn--primary"
          onClick={() => {
            if (padRef.current?.isEmpty()) {
              setSigned(null);
              return;
            }
            setSigned(padRef.current?.toDataURL('image/png') ?? null);
          }}
        >
          Sign van rental agreement
        </button>
      </div>
      {signed ? (
        <img className="b3-shot" src={signed} alt="Signature for the van rental agreement" />
      ) : (
        <p className="b3-hint">Draw your signature above, then sign. Works with touch and mouse.</p>
      )}
    </div>
  );
}

